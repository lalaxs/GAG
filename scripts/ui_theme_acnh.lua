-- ============================================================================
--
-- 动物森友会最显著的视觉特征: 一切都是圆润的
--
-- | 元素           | 圆角值 | 说明                     |
-- |---------------|--------|-------------------------|
-- | 主弹窗/面板    | 24px   | 超大圆角，气泡感          |
