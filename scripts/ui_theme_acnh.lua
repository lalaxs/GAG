-- ============================================================================
-- § 2. 字体规范 (Typography)
-- ============================================================================
--
-- 【字号体系】(单位: pt，实际渲染 ≈ pt × 1.333 = px)
--
-- | 层级         | pt  | ≈px | 用途                           |
-- |-------------|-----|-----|-------------------------------|
-- | display     | 28  | 37  | 游戏标题（"我的花园"）           |
-- | headline    | 20  | 27  | 页面标题、弹窗标题               |
-- | title       | 16  | 21  | 区域标题（"种子商店"、"背包"）    |
-- | subtitle    | 14  | 19  | 副标题、分组名                   |
-- | bodyLarge   | 13  | 17  | 主按钮文字、重要信息              |
-- | body        | 11  | 15  | 正文、列表项                     |
-- | bodySmall   | 10  | 13  | 辅助说明、种子属性               |
-- | small       | 9   | 12  | 时间倒计时、容量提示              |
-- | caption     | 8   | 11  | 角标、稀有度标记                 |
--
-- 【字重】
-- - normal: 正文、说明、提示
-- - bold:   标题、按钮、金额、稀有度
