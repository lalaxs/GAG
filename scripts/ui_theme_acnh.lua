-- ============================================================================
--
-- 【设计哲学】
-- 动物森友会的 UI 特征:
--   1. 圆润感 — 所有元素使用大圆角，无尖锐棱角
--   2. 柔和色 — 低饱和暖色系为主，粉绿/奶白/淡黄
--   3. 对话框 — 类手写信风格的卡片弹窗
--   4. 描边感 — 柔和的深色外描边代替硬阴影
--   5. 自然系 — 叶子绿、泥土棕、天空蓝贯穿始终
--   6. 大留白 — 宽松的内边距，不拥挤
--   7. 温馨字 — 圆润字体 + 适中字号 + 暖色文字
--
-- ============================================================================

