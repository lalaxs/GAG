-- ============================================================================
-- § 4. 描边规范 (Borders & Outlines)
-- ============================================================================
--
-- 动物森友会不使用硬阴影，而是用柔和描边表现层次
--
-- | 场景            | 描边宽度 | 颜色           | 说明                   |
-- |----------------|---------|----------------|------------------------|
-- | 主面板外框      | 3px     | 暖沙棕 60%透明  | 柔和的卡片边界          |
-- | 次级面板        | 2px     | 暖沙棕 40%透明  | 轻边框                  |
-- | 按钮（常态）    | 2px     | 按钮色加深版    | 底部描边模拟厚度感       |
-- | 按钮（按下）    | 0px     | -              | 按下时描边消失           |
-- | 输入框          | 2px     | 暖沙棕 50%透明  | 内嵌输入框感            |
-- | 分隔线          | 1px     | 米色调 30%透明  | 极轻的区域分割          |
--
-- 【阴影替代方案】
-- 使用底部内描边(glowShadow inset bottom)模拟按钮厚度，
-- 而非外部投影阴影。营造"圆润积木按钮"的手感。
--
-- ============================================================================

